const assert = require('node:assert/strict');
const {analyze,stats,rsi,fresh}=require('../app/src/main/assets/engine.js');
const now=Date.UTC(2026,10,12,6);
const series=(start,step,n=80)=>({asOf:now,price:start+step*(n-1),points:Array.from({length:n},(_,i)=>({c:start+step*i,t:now-(n-i-1)*86400000}))});
const gold=series(2000,5),dollar=series(110,-.1),yieldData=series(5,-.02);
assert.equal(analyze({},now).usable,false,'empty inputs cannot produce a forecast');
assert.equal(analyze({gold},now).usable,false,'gold-only trend is not a macro judgment');
assert.equal(analyze({gold:series(2000,5,25),dollar},now).usable,false,'unavailable MA60 cannot count as a usable factor');
assert.equal(analyze({gold,dollar,yield:yieldData},now).title,'当前因素偏多');
assert.equal(analyze({gold:series(2400,-5),dollar:series(100,.1),yield:series(3,.02)},now).title,'当前因素偏空');
assert.equal(analyze({gold,dollar:series(100,.1),yield:series(3,.02)},now).title,'多空因素分歧');
assert.equal(analyze({gold:{...gold,asOf:now-5*86400000},dollar,yield:yieldData},now).usable,false,'stale gold disables directional output');
assert.equal(analyze({gold,dollar:{...dollar,asOf:now-5*86400000},yield:{...yieldData,asOf:now-5*86400000}},now).usable,false,'stale macro factors cannot satisfy availability');
assert.equal(fresh({...gold,asOf:now+2*3600000},now),false,'future timestamps rejected');
assert.equal(rsi(Array(20).fill(100)),50);
assert.equal(rsi(Array.from({length:20},(_,i)=>100+i)),100);
assert.equal(rsi(Array.from({length:20},(_,i)=>100-i)),0);
assert.equal(stats(series(100,0)).vol,0);
assert.equal(stats(series(100,1,10)),null);
assert.equal(analyze({gold:{error:'offline'},dollar,yield:yieldData},now).usable,false);
console.log('PASS: 15 analytical checks (missing data, direction, conflict, staleness, RSI, volatility)');
