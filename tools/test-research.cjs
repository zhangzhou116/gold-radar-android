const assert=require('node:assert/strict');
const R=require('../app/src/main/assets/research.js');
const now=Date.UTC(2026,10,12,15);
const series=(n=80)=>({asOf:now,fetchedAt:now,source:'test',symbol:'test',price:2100,points:Array.from({length:n},(_,i)=>({t:now-(n-i)*86400000,c:2000+i}))});
const items=[1,2,3,4].map(i=>({title:'测试新闻 '+i,date:new Date(now-i*3600000).toISOString(),source:'test',url:'https://example.com/'+i,summary:'测试摘要'}));
const fixture={gold:series(),dollar:series(),yield:series(),oil:series(),news:{items,fetchedAt:now}};
const pack=R.prepare(fixture,now);assert.equal(pack.ready,true);
assert.equal(R.prepare({gold:series(),news:fixture.news},now).ready,false,'no cross-market data cannot trigger paid research');
assert.equal(R.prepare({...fixture,news:{items:items.map(x=>({...x,date:new Date(now-8*86400000).toISOString()})),fetchedAt:now}},now).ready,false,'old news rejected');
assert.equal(R.prepare({...fixture,gold:{...series(),fetchedAt:now-2*86400000}},now).ready,false,'old cached fetch rejected');
assert.equal(R.prepare({...fixture,geo:fixture.news},now).evidence.filter(x=>x.kind==='news').length,4,'identical repost titles deduplicated');
assert.equal(R.prepare({...fixture,news:{items:items.map(x=>({...x,date:new Date(now+7200000).toISOString()})),fetchedAt:now}},now).ready,false,'future news rejected');
const report={summary:'测试',regime:'测试',newsImpact:'测试',crossMarket:'测试',bullCase:'测试',bearCase:'测试',risks:['测试'],watch:['测试'],reviewNotes:'测试',horizons:[1,3,5].map(days=>({days,direction:'bullish',reason:'行情与新闻依据',invalidate:'测试条件',evidence:['GOLD','N1']}))};
assert.equal(R.validate(report,pack),report);
const clone=()=>JSON.parse(JSON.stringify(report));
let bad=clone();bad.horizons[0].evidence=['GOLD','N999'];assert.throws(()=>R.validate(bad,pack),/不存在/);
bad=clone();bad.horizons[0].evidence=['GOLD'];assert.throws(()=>R.validate(bad,pack),/同时引用/);
bad=clone();bad.horizons[1].days=1;assert.throws(()=>R.validate(bad,pack),/周期/);
bad=clone();bad.summary='上涨概率90%';assert.throws(()=>R.validate(bad,pack),/概率或准确率/);
const decision=Date.UTC(2026,10,2,15),receipt={generatedAt:decision,report:clone(),results:{}};
const points=Array.from({length:9},(_,i)=>({t:Date.UTC(2026,10,2+i,15),c:100+i}));
let settled=R.settle(receipt,{points},Date.UTC(2026,10,4,16));
assert.equal(Object.keys(settled.results).length,0,'current-day bar not used for exit');
settled=R.settle(receipt,{points},Date.UTC(2026,10,10,16));
assert.equal(settled.results[1].entry,101,'entry uses first later NY date');
assert.equal(settled.results[1].exit,102,'one-day horizon needs one further completed bar');
assert.equal(settled.results[1].outcome,'correct');
assert.equal(Object.keys(receipt.results).length,0,'receipt input stays immutable');
const wait={...receipt,report:clone()};wait.report.horizons[0].direction='wait';
assert.equal(R.settle(wait,{points},Date.UTC(2026,10,10,16)).results[1].outcome,'abstained');
const flat={points:points.map(p=>({...p,c:100}))};
assert.equal(R.settle(receipt,flat,Date.UTC(2026,10,10,16)).results[1].outcome,'wrong','flat results do not pad directional accuracy');
const again=R.settle(settled,{points:points.map(p=>({...p,c:20}))},Date.UTC(2026,10,11,16));
assert.equal(again.results[1].exit,102,'settled results cannot be rewritten by later revisions');
console.log('PASS: 19 research checks: evidence freshness, deduplication, citation guards, probability refusal, forward-only settlement, abstention and immutable results');
