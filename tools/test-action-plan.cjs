const assert=require('node:assert/strict');
const P=require('../app/src/main/assets/action-plan.js');
const pack={byId:{GOLD:{price:4000,points:[{c:3900},{c:4100}]},N1:{kind:'news'}}};
const zone=(low,high,percent)=>({low,high,percent,condition:'等待确认',basis:'日线支撑或阻力参考',evidence:['GOLD']});
const plan={status:'wait',headline:'等待回落确认',instrument:'GC=F',unit:'USD/oz',referencePrice:4000,validForHours:12,waitFor:'确认支撑',invalidate:'重大事件',buy:[zone(3900,3920,20),zone(3850,3880,30)],sell:[zone(4050,4100,30)],stopPrice:3800,evidence:['GOLD','N1']};
assert.equal(P.validate(plan,pack),plan);
const bad=edit=>{const p=JSON.parse(JSON.stringify(plan));edit(p);assert.throws(()=>P.validate(p,pack));};
bad(p=>p.referencePrice=3999);
bad(p=>p.unit='CNY/g');
bad(p=>p.buy[0].percent=80);
bad(p=>p.buy[0].low=NaN);
bad(p=>p.sell[0].low=3800);
bad(p=>p.stopPrice=3900);
bad(p=>p.buy[0].evidence=['INVENTED']);
