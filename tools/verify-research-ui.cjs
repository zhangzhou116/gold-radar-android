const {chromium}=require('playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  const context=await browser.newContext({viewport:{width:393,height:851},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  await context.addInitScript(()=>{
    window.testCalls=[];
    window.GoldNative={refresh(){},open(){},aiSettings(){},aiStatus(){setTimeout(()=>window.onNativeData('aiStatus',{configured:true,provider:'TEST ONLY',model:'TEST ONLY'}),0);},analyze(s){window.testCalls.push(JSON.parse(s));}};
  });
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',()=>{throw Error('Research must start without a confirmation dialog');});
  await page.goto('http://127.0.0.1:8765/');
  await page.locator('[data-page="analysis"]').click();
  await page.locator('#aiRun').click();
  assert.equal(await page.evaluate(()=>testCalls.length),0,'insufficient evidence must not trigger a paid call');
  const fixture=JSON.parse(fs.readFileSync(path.join(__dirname,'../build/live-data.json'),'utf8'));
  for(const [k,v]of Object.entries(fixture))await page.evaluate(([k,v])=>onNativeData(k,v),[k,v]);
  await page.evaluate(()=>onNativeData('done',{}));
  assert.match(await page.locator('#evidenceStatus').innerText(),/可开始研判/);
  await page.locator('#aiRun').click();
  assert.equal(await page.evaluate(()=>testCalls.length),1);
  assert.equal(await page.evaluate(()=>!!testCalls[0].byId),false,'prompt must not duplicate the evidence lookup');
  assert.equal(await page.locator('#aiRun').isDisabled(),true);
  assert.equal(await page.locator('#aiRun').getAttribute('aria-busy'),'true');
  assert.match(await page.locator('#aiRun').innerText(),/正在综合研判/);
  await page.locator('#aiRun').evaluate(el=>el.click());
  assert.equal(await page.evaluate(()=>testCalls.length),1,'loading blocks duplicate calls');
  const mockReport={summary:'测试报告，不是真实研判',regime:'测试市场',newsImpact:'测试新闻',crossMarket:'测试跨市场',bullCase:'测试多头',bearCase:'测试空头',risks:['测试风险'],watch:['测试观察'],reviewNotes:'测试复核',horizons:[1,3,5].map(days=>({days,direction:'wait',reason:'测试理由',invalidate:'测试失效条件',evidence:['GOLD','N1']}))};
  mockReport.actionPlan={status:'wait',headline:'测试条件参考',instrument:'GC=F',unit:'USD/oz',referencePrice:fixture.gold.price,validForHours:12,waitFor:'等待日线确认',invalidate:'重大事件',buy:[],sell:[],stopPrice:null,evidence:['GOLD']};
  const price=fixture.gold.price;
  const zone=(low,high,percent)=>({low,high,percent,condition:'测试触发条件 <img src=x onerror=alert(1)>',basis:'测试日线依据',evidence:['GOLD']});
  mockReport.actionPlan.buy=[zone(price*.98,price*.99,20),zone(price*.96,price*.97,30)];
  mockReport.actionPlan.sell=[zone(price*1.02,price*1.03,30)];
  mockReport.actionPlan.stopPrice=price*.95;
  await page.evaluate(r=>onNativeData('aiResult',{report:r,draft:r,provider:'TEST ONLY',model:'TEST ONLY',generatedAt:Date.now()}),mockReport);
  assert.equal(await page.locator('.horizon').count(),3);
  assert.equal(await page.locator('.decision-board').count(),1);
  assert.equal(await page.locator('.price-step').count(),3);
  assert.match(await page.locator('.decision-board').innerText(),/现在先等一等/);
  assert.match(await page.locator('.decision-board').innerText(),/预留资金 50%/);
  assert.equal(await page.locator('.decision-board img').count(),0,'model text is escaped');
  assert.equal(await page.locator('.price-chart svg polyline').count(),1);
  const cny=await page.locator('.board-prices strong').first().innerText();
  assert.match(await page.locator('.board-unit').first().innerText(),/人民币/);
  assert.equal(cny,(price*fixture.fx.price/31.1034768).toLocaleString('en-US',{minimumFractionDigits:2,maximumFractionDigits:2}));
  await page.locator('[data-gold-currency="USD"]').click();
  assert.equal(await page.locator('.board-prices strong').first().innerText(),price.toLocaleString('en-US',{minimumFractionDigits:2,maximumFractionDigits:2}));
  await page.locator('[data-gold-currency="CNY"]').click();
  assert.equal(await page.locator('.board-prices strong').first().innerText(),cny);
  const narrative=await page.evaluate(()=>moneyNarrative('2026年，'+testCalls[0].evidence.find(x=>x.id==='GOLD').price+'；仓位20%',JSON.parse(localStorage.getItem('gold-research-v1'))[0]));
  assert.match(narrative,/2026年/);assert.match(narrative,/元\/克/);assert.match(narrative,/仓位20%/);
  await page.locator('.decision-board').screenshot({path:'/tmp/gold-board-393.png'});
  assert.match(await page.locator('#forecastHistory').innerText(),/待验证/);
  assert.match(await page.locator('#forecastHistory').innerText(),/观望 1/);
  assert.equal(await page.locator('#aiRun').isDisabled(),false);
  assert.equal(await page.locator('#aiRun').getAttribute('aria-busy'),'false');
  await page.reload();await page.locator('[data-page="analysis"]').click();
  assert.match(await page.locator('#researchReport').innerText(),/测试报告/,'receipt survives reload');
  await page.locator('#aiRun').click();
  const bad=JSON.parse(JSON.stringify(mockReport));bad.horizons[0].evidence=['INVENTED'];
  await page.evaluate(r=>onNativeData('aiResult',{report:r,draft:r,provider:'TEST ONLY',model:'TEST ONLY',generatedAt:Date.now()}),bad);
  assert.match(await page.locator('#aiProgress').innerText(),/未发布/);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('gold-research-v1')).length),1,'invalid report cannot pollute history');
  await page.locator('#aiRun').click();
  const invalidPlan=JSON.parse(JSON.stringify(mockReport));invalidPlan.actionPlan.buy[0].percent=101;
  await page.evaluate(r=>onNativeData('aiResult',{report:r,provider:'TEST ONLY',model:'TEST ONLY',generatedAt:Date.now()}),invalidPlan);
  assert.match(await page.locator('#aiProgress').innerText(),/未发布/);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('gold-research-v1')).length),1,'invalid allocation never enters saved reports');
  await page.evaluate(()=>{const r=JSON.parse(localStorage.getItem('gold-research-v1'))[0];r.generatedAt=Date.now()-2*86400000;renderReport(r);});
  assert.match(await page.locator('.decision-board h2').innerText(),/已过期/);
  await page.evaluate(()=>{const r=JSON.parse(localStorage.getItem('gold-research-v1'))[0];delete r.report.actionPlan;renderReport(r);});
  assert.match(await page.locator('.plan-empty').innerText(),/旧报告/);
  await page.evaluate(()=>renderReport(JSON.parse(localStorage.getItem('gold-research-v1'))[0]));
  assert.deepEqual(errors,[]);
  await page.setViewportSize({width:320,height:740});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('.decision-board').screenshot({path:'/tmp/gold-board-320.png'});
  console.log('PASS: no-dialog loading, allocation dashboard, price chart, XSS escaping, invalid plans rejected, expiry, legacy reports, receipts and 320/393px layouts; no JS errors. Mock output stayed in isolated browser test only.');
  await context.clearCookies();await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
