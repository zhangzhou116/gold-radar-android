const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  const context=await browser.newContext({viewport:{width:393,height:851},deviceScaleFactor:2,isMobile:true,hasTouch:true});
  const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/');
  assert.equal(await page.locator('#verdictTitle').innerText(),'等待足够数据');
  const fixture=JSON.parse(fs.readFileSync(path.join(__dirname,'../build/live-data.json'),'utf8'));
  for(const [k,v]of Object.entries(fixture))await page.evaluate(([k,v])=>window.onNativeData(k,v),[k,v]);
  await page.evaluate(()=>window.onNativeData('done',{}));
  assert.notEqual(await page.locator('#goldPrice').innerText(),'—');
  assert.equal(await page.locator('#chart path').count(),4);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile viewport must not overflow');
  await page.screenshot({path:path.join(__dirname,'../dist/preview-home.png'),fullPage:true});
  await page.locator('nav [data-page="analysis"]').click();
  assert.equal(await page.locator('#factors article').count(),4);
  assert.equal(await page.locator('#scenarios .scenario-row').count(),1);
  await page.screenshot({path:path.join(__dirname,'../dist/preview-analysis.png'),fullPage:true});
  await page.locator('nav [data-page="news"]').click();
  await page.evaluate(()=>window.onNativeData('news',{items:[{title:'<img src=x onerror="alert(1)">',url:'https://example.com/',source:'UI safety test',date:'2026-11-12T00:00:00Z'}],fetchedAt:Date.now()}));
  assert.equal(await page.locator('#newsList img').count(),0,'news must not inject HTML');
  await page.locator('nav [data-page="settings"]').click();
  assert.equal(await page.locator('#sources .source').count(),15);
  await page.evaluate(()=>window.onNativeData('gold',{error:'network unavailable'}));
  assert.match(await page.locator('#sources').innerText(),/本次失败/);
  assert.ok((await page.locator('#goldPrice').innerText()).length>1,'failed refresh preserves data');
  await page.reload();
  assert.match(await page.locator('#verdictTag').innerText(),/缓存/);
  await page.setViewportSize({width:320,height:740});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'small phone viewport must not overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS: mobile 393/320px, navigation, live-data rendering, source failures, cache reload, news HTML escaping; no JS errors');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
